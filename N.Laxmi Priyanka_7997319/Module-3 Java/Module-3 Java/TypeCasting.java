public class TypeCasting {
    public static void main(String[] args) {
        int i=5;
        double d=3.75;
        System.out.println("Original Integer:"+i);
        double cast=i;
        System.out.println("Integer after type casting:"+cast);
        System.out.println("Original Double:"+d);
        System.out.println("Double after type casting:"+(int) d);
    }
}
