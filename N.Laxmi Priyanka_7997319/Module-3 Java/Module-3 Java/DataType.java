public class DataType {
    public static void main(String[] args) {
        int a=5;
        float b=3.14f;
        double c=8.7;
        char ch='A';
        boolean bool=true;
        System.out.println("Integer:"+a);
        System.out.println("Float:"+b);
        System.out.println("Double:"+c);
        System.out.println("Character:"+ch);
        System.out.println("Boolean:"+bool);
    }
}
